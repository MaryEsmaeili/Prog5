# Import necessary libraries
import configparser
from pyspark.sql import SparkSession

# Initialize SparkSession with the path to MariaDB JDBC driver and ANSI mode disabled
spark = SparkSession.builder \
    .appName("dbNSFP to MySQL") \
    .master("local[*]") \
    .config("spark.jars.packages", "org.mariadb.jdbc:mariadb-java-client:3.5.0") \
    .config("spark.sql.ansi.enabled", "false") \
    .getOrCreate()

# Step 1: Load configuration from .my.cnf
config_path = '/homes/mesmaeili/.my.cnf'
config = configparser.ConfigParser()
config.read(config_path)

# Build the database URL and connection properties
db_url = f"jdbc:mariadb://{config['client']['host']}:3306/{config['client']['database']}"
db_properties = {
    "user": config["client"]["user"],
    "password": config["client"]["password"],
    "driver": "org.mariadb.jdbc.Driver"
}

# Step 2: Load gzipped data (sampling 1000 rows for testing)
df = spark.read \
    .format("csv") \
    .option("header", "true") \
    .option("sep", "\t") \
    .option("compression", "gzip") \
    .load("/data/datasets/dbNSFP/snpEff/data/dbNSFP4.9a.txt.gz") \
    .limit(1000)

# Show the schema of the loaded DataFrame
df.printSchema()

# Stop Spark session
spark.stop()


